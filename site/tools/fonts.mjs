// Vendor the site's typefaces into site/fonts/ as self-hosted woff2.
//
// The site never touches a font CDN at runtime: no third-party connection on
// the critical path, no flash of unstyled text waiting on someone else's DNS.
// This script pulls the variable woff2 files from Google Fonts once and writes
// a matching fonts.css next to them. Re-run only when changing families:
//
//     node site/tools/fonts.mjs
//
// Only the latin and latin-ext subsets are kept — the site copy is English, and
// dropping cyrillic/greek/vietnamese roughly halves each file.

import { writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'fonts')

// Chrome UA so the API serves variable woff2 rather than legacy formats.
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'

// Display is Unbounded: it is the closest freely-licensable analogue to the
// e-Ukraine face Diia uses — squared geometric skeleton, flat-sided rounds,
// and a weight 800 that stays sharp at poster size. Text is Onest, a screen-
// first grotesque from the same modernist lineage that is quietly squared
// enough to agree with Unbounded without competing with it.
const FAMILIES = [
  { query: 'Unbounded:wght@600..900', family: 'Unbounded', file: 'unbounded', display: 'swap' },
  { query: 'Onest:wght@300..800', family: 'Onest', file: 'onest', display: 'swap' },
  { query: 'JetBrains+Mono:wght@400..600', family: 'JetBrains Mono', file: 'jetbrains-mono', display: 'swap' },
]

// The two subsets worth keeping, identified by their unicode-range signature.
const KEEP = [
  { name: 'latin-ext', match: 'U+0100-02BA' },
  { name: 'latin', match: 'U+0000-00FF' },
]

mkdirSync(OUT, { recursive: true })

/** Split the Google Fonts stylesheet into one record per @font-face block. */
function parseFaces(css) {
  return [...css.matchAll(/\/\*\s*([\w-\[\]]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)].map(
    ([, subset, body]) => ({
      subset,
      body,
      url: body.match(/url\((https:[^)]+)\)/)?.[1],
      range: body.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim(),
      weight: body.match(/font-weight:\s*([^;]+);/)?.[1]?.trim(),
      style: body.match(/font-style:\s*([^;]+);/)?.[1]?.trim() ?? 'normal',
      variations: body.match(/font-variation-settings:\s*([^;]+);/)?.[1]?.trim(),
    })
  )
}

const rules = []

for (const { query, family, file, display } of FAMILIES) {
  const css = await fetch(`https://fonts.googleapis.com/css2?family=${query}&display=${display}`, {
    headers: { 'User-Agent': UA },
  }).then((r) => r.text())

  const faces = parseFaces(css)

  for (const { name, match } of KEEP) {
    const face = faces.find((f) => f.range?.includes(match) && f.url)
    if (!face) {
      console.warn(`${family}: no ${name} subset found, skipping`)
      continue
    }

    const outName = `${file}-${name}.woff2`
    const bytes = Buffer.from(await fetch(face.url).then((r) => r.arrayBuffer()))
    writeFileSync(join(OUT, outName), bytes)
    console.log(`${outName}: ${(bytes.length / 1024).toFixed(1)} KB`)

    rules.push(
      [
        '@font-face {',
        `  font-family: "${family}";`,
        `  font-style: ${face.style};`,
        `  font-weight: ${face.weight};`,
        face.variations ? `  font-variation-settings: ${face.variations};` : null,
        `  font-display: ${display};`,
        `  src: url("./${outName}") format("woff2-variations");`,
        `  unicode-range: ${face.range};`,
        '}',
      ]
        .filter(Boolean)
        .join('\n')
    )
  }
}

const header = [
  '/* Self-hosted variable fonts. Generated by site/tools/fonts.mjs — do not edit by hand.',
 '',
  ' * Unbounded, Inter and JetBrains Mono are all licensed under the SIL Open Font License 1.1.',
  ' */',
  '',
].join('\n')

writeFileSync(join(OUT, 'fonts.css'), `${header}${rules.join('\n\n')}\n`)
console.log(`wrote ${join(OUT, 'fonts.css')}`)
