// Regenerate only from the reviewed URL + SHA-256 inventory. Updating fonts
// requires reviewing font-sources.json, including the immutable OFL sources.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { replaceDirectory, sha256 } from './generation.mjs'

function validateFont(bytes) {
  if (bytes.length < 48 || bytes.toString('ascii', 0, 4) !== 'wOF2' || bytes.readUInt32BE(8) !== bytes.length) {
    throw new Error('Invalid WOFF2 header or length')
  }
}

async function download(source, fetchImpl, kind) {
  const url = new URL(source.url)
  const allowed = kind === 'font' ? url.hostname === 'fonts.gstatic.com' :
    url.hostname === 'raw.githubusercontent.com' && /^\/google\/fonts\/[a-f0-9]{40}\/ofl\//.test(url.pathname)
  if (url.protocol !== 'https:' || !allowed) throw new Error(`Untrusted ${kind} source: ${url}`)
  const response = await fetchImpl(url, { signal: AbortSignal.timeout(15000), redirect: 'error' })
  if (!response.ok) throw new Error(`HTTP ${response.status}: ${url}`)
  const type = response.headers.get('content-type')?.split(';')[0]
  if (kind === 'font' && !['font/woff2', 'application/font-woff2', 'application/octet-stream'].includes(type)) {
    throw new Error(`Unexpected font content type: ${type}`)
  }
  if (Number(response.headers.get('content-length')) > 2_000_000) throw new Error('Font source too large')
  const bytes = Buffer.from(await response.arrayBuffer())
  if (!bytes.length || bytes.length > 2_000_000 || sha256(bytes) !== source.sha256) throw new Error(`Digest/size mismatch: ${url}`)
  if (kind === 'font') validateFont(bytes)
  else if (!bytes.toString().includes('SIL OPEN FONT LICENSE Version 1.1')) throw new Error('Expected OFL 1.1 license')
  return bytes
}

function validateManifest(manifest) {
  const faces = manifest.faces
  if (!Array.isArray(faces) || faces.length !== 6 || new Set(faces.map(face => face.file)).size !== 6) {
    throw new Error('Expected six unique faces in the complete font set')
  }
  const families = new Set(faces.map(face => face.family))
  if (!Array.isArray(manifest.licenses) || manifest.licenses.length !== 3 ||
      [...families].some(family => manifest.licenses.filter(license => license.family === family).length !== 1)) {
    throw new Error('Expected one license notice for each font family')
  }
  if (families.size !== 3 || [...families].some(family =>
    ['latin', 'latin-ext'].some(subset => faces.filter(face => face.family === family && face.subset === subset).length !== 1))) {
    throw new Error('Expected complete latin and latin-ext subsets for three families')
  }
  if (new Set([...faces, ...manifest.licenses].map(source => source.file)).size !== 9) throw new Error('Duplicate font/license output filename')
  for (const source of [...faces, ...manifest.licenses]) {
    if (!/^[a-z0-9-]+\.(woff2|txt)$/.test(source.file) || !/^[a-f0-9]{64}$/.test(source.sha256)) throw new Error('Invalid font source name/digest')
  }
  for (const face of faces) {
    if (!/^[\w -]+$/.test(face.family) || !/^\d+ \d+$/.test(face.weight) || face.style !== 'normal' || !/^[U+0-9A-Fa-f,? -]+$/.test(face.range)) {
      throw new Error('Invalid font CSS metadata')
    }
  }
}

function rule(face, build) {
  const query = build === undefined ? '' : `?v=${build}`
  return `@font-face {\n  font-family: "${face.family}";\n  font-style: normal;\n  font-weight: ${face.weight};\n  font-display: swap;\n  src: url("./${face.file}${query}") format("woff2");\n  unicode-range: ${face.range};\n}`
}

export function renderFontCSS(manifest, build) {
  validateManifest(manifest)
  if (build !== undefined && !/^[A-Za-z0-9]+$/.test(build)) throw new Error('Invalid font CSS build ID')
  return '/* Generated by site/tools/fonts.mjs. SIL OFL 1.1 notices in licenses/. */\n' + manifest.faces.map(face => rule(face, build)).join('\n\n') + '\n'
}

export async function generateFonts({ out, manifest, fetchImpl = fetch }) {
  const css = renderFontCSS(manifest)
  await replaceDirectory(out, async staged => {
    await mkdir(join(staged, 'licenses'))
    for (const face of manifest.faces) await writeFile(join(staged, face.file), await download(face, fetchImpl, 'font'))
    for (const license of manifest.licenses) await writeFile(join(staged, 'licenses', license.file), await download(license, fetchImpl, 'license'))
    await writeFile(join(staged, 'fonts.css'), css)
    await writeFile(join(staged, 'provenance.json'), JSON.stringify(manifest, null, 2) + '\n')
  })
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const manifest = JSON.parse(await readFile(new URL('font-sources.json', import.meta.url), 'utf8'))
  await generateFonts({ out: fileURLToPath(new URL('../fonts', import.meta.url)), manifest })
  console.log('Generated six verified font subsets with OFL licenses and provenance')
}
